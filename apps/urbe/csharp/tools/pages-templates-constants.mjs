// Generates csharp/src/Urbe.Core/Pages/PageTemplatesText.g.cs: the built-in page templates of the 1.8.4
// (src/pages/templates.js) and the format reference (engine.js schemaText), evaluated from the original source.
// Each template is built with marked values for what the person gives (title, folder, note) and a marked date, so the
// native code fills in the real ones (PageTemplates); one variant per combination of given/absent values, because the
// templates pick defaults when a value is missing. Every value is checked by csharp/tools/pages-templates-oracle.mjs.
//
//   node csharp/tools/pages-templates-constants.mjs > csharp/src/Urbe.Core/Pages/PageTemplatesText.g.cs
import { readFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
// the marked "now": 15/01/7000 12:00 UTC (years 7000, 6998… and dates never appear in a template by themselves)
const T0 = Date.UTC(7000, 0, 15, 12);
const RD = Date;
function FD(...a) { if (!new.target) return RD(); return a.length ? new RD(...a) : new RD(T0); }
FD.prototype = RD.prototype; FD.now = () => T0; FD.UTC = RD.UTC; FD.parse = RD.parse;

const ctx = { console, JSON, Object, Array, String, Number, Math, RegExp, Error, isFinite, encodeURIComponent, Date: FD };
ctx.window = ctx; ctx.globalThis = ctx;
vm.createContext(ctx);
for (const f of ['engine.js', 'free.js', 'templates.js']) vm.runInContext(readFileSync(join(root, 'src/pages', f), 'utf8'), ctx, { filename: f });
const P = ctx.UrbePages, TPL = ctx.UrbePageTemplates;

const T = '⟦T⟧', D = '⟦D⟧', L = '⟦L⟧', NT = '⟦NT⟧', NP = '⟦NP⟧';
const templates = TPL.list().map(t => {
  const variants = {};
  for (const title of [0, 1]) for (const folder of [0, 1]) for (const note of [0, 1]) {
    if (folder && t.needs !== 'folder') continue;
    if (note && t.needs !== 'note') continue;
    // as pages/ai-tools.js builds it: c = {title, folder}; with a note, c.note and c.title = c.title || note title
    const c = { title: title ? T : '', folder: folder ? D + '/' + L : '' };
    if (note) { c.note = { title: NT, path: NP }; c.title = c.title || NT; }
    variants['t' + title + 'f' + folder + 'n' + note] = JSON.stringify(TPL.build(t.id, c));
  }
  return { id: t.id, name: t.name, icon: t.icon, description: t.description, needs: t.needs || null, variants };
});

function cs(s) {
  return '"' + Array.from(s).map(c => {
    const n = c.codePointAt(0);
    if (c === '\\') return '\\\\';
    if (c === '"') return '\\"';
    if (c === '\n') return '\\n';
    if (c === '\r') return '\\r';
    if (c === '\t') return '\\t';
    if (n < 32 || n > 126) return n > 0xffff ? '\\U' + n.toString(16).padStart(8, '0') : '\\u' + n.toString(16).padStart(4, '0');
    return c;
  }).join('') + '"';
}
const consts = {
  TemplatesJson: JSON.stringify(templates),
  SchemaText: P.schemaText(),
  ThemesList: Object.keys(P.THEMES).map(k => k + ' (' + P.THEMES[k].label + ', ' + P.THEMES[k].mode + ')').join(', ')
};
let out = '// <auto-generated>\n// Generated by csharp/tools/pages-templates-constants.mjs from apps/urbe/src/pages/templates.js and engine.js (Urbe 1.8.4-beta).\n// Do not edit: regenerate.\n// </auto-generated>\nnamespace Urbe.Core.Pages;\n\ninternal static class PageTemplatesText\n{\n';
for (const [k, v] of Object.entries(consts)) out += '    public const string ' + k + ' = ' + cs(v) + ';\n';
out += '}\n';
process.stdout.write(out);
